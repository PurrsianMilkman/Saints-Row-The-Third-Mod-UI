-- Example SR3 Mod UI script mod. Copy to <game>\SR3ModUI\mods\ and it appears in Pause > MODS.
-- Every widget type, each logging what it got to SR3ModUI.log.
local page = ModUI.page("example", "Example Mod")

page:label("about", "SR3 Mod UI example page")
page:toggle("enabled", "Enabled", true, function(on)
	ModUI.log("example: enabled =", on)
end)
page:slider("amount", "Amount", 0, 5, 0.5, 2.5, function(v)
	ModUI.log("example: amount =", v)
end)
page:choice("mode", "Mode", { "Calm", "Busy", "Chaos" }, 1, function(i, name)
	ModUI.log("example: mode =", i, name)
end)
page:color("tint", "Tint", 0x3080FF, function(rgb, r, g, b)
	ModUI.log("example: tint =", ModUI.fmt(r, 2), ModUI.fmt(g, 2), ModUI.fmt(b, 2))
end)
page:label("long", "A long line of text, much wider than the stock pause panel is")
page:toggle("long_toggle", "A toggle with a fairly long label as well", false)
page:color("long_color", "Colour row with a long label next to its swatch", 0xFF8000)
page:button("hello", "Say hello", function()
	ModUI.log("example: hello pressed")
	page:set_label("about", "Hello pressed!")
end)
